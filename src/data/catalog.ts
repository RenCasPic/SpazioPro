function fixSwatch(s: string): string {
  // guard against any malformed seeds — fall back to a neutral swatch
  return /^(#|rgb|hsl|linear-gradient|radial-gradient|repeating-)/.test(s.trim())
    ? s
    : "linear-gradient(120deg,#d9d4c9,#b7b2a7)";
}

export const CATALOG: Product[] = seed.map((p) => ({
  ...p,
  group: p.group ?? categoryMeta(p.category).group,
  swatch: fixSwatch(p.swatch),
}));

export const productById = (id: string): Product | undefined =>
  CATALOG.find((p) => p.id === id);
